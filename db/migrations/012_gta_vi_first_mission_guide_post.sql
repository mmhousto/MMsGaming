<h2>Part 2: Gone Fishing (Jason&rsquo;s first mission)</h2>
<p>Now the real checklist begins! In Gone Fishing, a smuggling run with Cal and Donnie goes sideways, and Jason has to head into Kingfishers territory to get Donnie back. Here is what most people miss.</p>

<p><strong>1. Start your animal collection.</strong> Early in the mission you equip binoculars (bottom-right slot of the weapon wheel) to watch a deal. Keep them handy: you can use them to <strong>study animals</strong>, and studying 100 of the game&rsquo;s 255 species counts toward 100% completion. Progress you make during the story already counts, so start now.</p>

<p><strong>2. Go in quiet.</strong> You can clear the Kingfishers camp without firing a shot. Stay crouched, sneak up behind enemies and choke them out. Clicking the left stick while crouched lets you move faster without being heard. Playing it stealthy earns <strong>Professional</strong> reputation. Lost? Look for the big turbine: the shack you need is in the far corner of the camp, and the game lets you hold the right stick to look toward points of interest.</p>

<div class="post-tip"><p><strong>Pro tip, reputation matters:</strong> GTA VI tracks how you play. Stealth builds <strong>Professional</strong> reputation, shooting enemies in the limbs builds <strong>Hardened</strong>, killing builds <strong>Psychopath</strong>, and killing cops or civilians can make you <strong>Irredeemable</strong>. At the two worst levels, police may open fire on sight, so aim for the legs if you want to stay on their good side.</p></div>

<p><strong>3. Grab the Zombix.</strong> After you untie Donnie and deal with the brute who bursts in, pick up the <strong>Zombix</strong> in the shack. It is GTA VI&rsquo;s healing item. You can carry up to five at a time and buy more at convenience stores.</p>

<p><strong>4. Don&rsquo;t miss the trailer cash!</strong> This is the big one. On your way to the seaplane, Donnie will call out that your cash is stashed in a <strong>white-and-red trailer on the left</strong>. Head inside, win the scuffle (watch for the quick-time prompt), take out the enemy and grab the money. It is optional, it earns <strong>Professional</strong> reputation, and once you fly away it is gone for good. So whatever you do, don&rsquo;t sprint straight to the plane.</p>

